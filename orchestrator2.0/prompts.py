def analyze_prompt():
    """ANALYZE_PROMPT 的图参数化版本：把 [[dep_rel]]/[[hosting_rel]] 换成
    当前图核心语义（core_semantics），换图后无需改提示词。"""
    import gateway
    sem = gateway.core_semantics()
    prompt = (ANALYZE_PROMPT
            .replace(u"[[dep_rel]]", _text(sem.get("dependency_rel")) or u"依赖")
            .replace(u"[[hosting_rel]]",
                     _text(sem.get("hosting_rel")) or u"承载"))
    if not _text(sem.get("dependency_rel")).strip():
        prompt = (u"【当前图特别规则】当前 Schema 没有定义依赖传播关系。禁止把包括、承载、"
                  u"执行、隶属、协同等结构或关联关系判定为依赖或确定性受影响对象；"
                  u"只能按真实边方向列为关联检查范围。\n\n" + prompt)
